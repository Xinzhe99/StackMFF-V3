# ---------------- V6 Q^{AB/F}: N=2 generalization vs independent reference
sect('V6. Q^{AB/F} for N=2 vs independent pixel-loop reference (Xydeas and Petrovic 2000)')
def sobel_conv(img):
    x = img.astype(np.float64); H, W = x.shape
    P_ = np.pad(x, 1)
    kx = np.array([[-1, 0, 1], [-2, 0, 2], [-1, 0, 1]], float)
    ky = np.array([[1, 2, 1], [0, 0, 0], [-1, -2, -1]], float)
    gx = np.zeros((H, W)); gy = np.zeros((H, W))
    for u in (-1, 0, 1):
        for v in (-1, 0, 1):
            sl = P_[1 - u:1 - u + H, 1 - v:1 - v + W]  # img(i-u, j-v)
            gx += kx[u + 1, v + 1] * sl
            gy += ky[u + 1, v + 1] * sl
    return gx, gy

def qabf_ref(A, B, F):
    Tg, kg, Dg, Ta, ka, Da = 0.9994, -15, 0.5, 0.9879, -22, 0.8
    sA = sobel_conv(A); sB = sobel_conv(B); sF = sobel_conv(F)
    H, W = F.shape
    num = 0.0; den = 0.0
    def ga(s):
        return math.hypot(s[0], s[1])
    def an(s):
        return math.pi / 2 if s[0] == 0 else math.atan(s[1] / s[0])
    for i in range(H):
        for j in range(W):
            sf = (sF[0][i, j], sF[1][i, j]); gf = math.hypot(*sf); af = an(sf)
            for src in (sA, sB):
                s = (src[0][i, j], src[1][i, j]); g = math.hypot(*s); a = an(s)
                if g > gf: G = gf / g
                elif g < gf: G = g / gf
                else: G = 1.0 if g > 0 else 0.0
                Qg = Tg / (1 + math.exp(kg * (G - Dg)))
                Aa = 1 - abs(a - af) / (math.pi / 2)
                Qa = Ta / (1 + math.exp(ka * (Aa - Da)))
                num += g * Qg * Qa; den += g
    return num / den

